/// Root of a depth-`CIRCUIT_DEPTH` Merkle tree whose ONLY leaf is `leaf`, at
/// index 0 — i.e. `insert_leaf` into a fresh tree, minus the bookkeeping.
///
/// This is the whole of F35-R2. `member_vote.circom` constrains only
/// `root === cur[depth]`; it says nothing about WHICH set `root` denotes, so
/// 100% of that meaning lives in the program's root check. Pointing that check
/// at *the tree whose single leaf is the wing's commitment* means the only
/// witness that can satisfy it is a secret `s` with `Poseidon(s) == wing` —
/// mandatory sponsorship, with no sponsor account and no sponsor wallet in the
/// transaction.
///
/// INVARIANT — this value must NEVER be pushed into `RecentRoots`. Every entry
/// of that ring is a genuine historical `member_tree.root` written by a
/// seed-checked instruction, and `attest_admission_zk`'s soundness rests
/// entirely on that. A synthetic single-leaf root in the ring would let one
/// commitment-holder pass the admission gate as though they had proved
/// membership of the whole tree — including a commitment that is not in the tree
/// at all. Compute it locally, in `activate_faucet_zk`, and nowhere else.
///
/// Fails CLOSED: `poseidon2` rejects a non-field input, so an out-of-field
/// `leaf` surfaces as `PoseidonError` rather than as an accepted endorsement.
/// (It cannot happen on a real bond — `issue_membership` feeds every commitment
/// through `insert_leaf` → `poseidon2` before it can become a `Membership`.)
pub fn single_leaf_root(leaf: &[u8; 32]) -> Result<[u8; 32]> {
    let mut cur = *leaf;
    for i in 0..(CIRCUIT_DEPTH as usize) {
        cur = poseidon2(&cur, &WING_ZEROS[i])?;
    }
    Ok(cur)
}
